#!/usr/bin/env python3
"""Generate navigation, indexes and counts; --check is a read-only CI gate."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re

from content_catalog import build_catalog, md_link, relative, title_of
from generate_keywords import render_keywords
from lib_config import ROOT


def replace_block(text: str, name: str, body: str) -> str:
    start, end = f"<!-- BEGIN GENERATED:{name} -->", f"<!-- END GENERATED:{name} -->"
    pattern = re.escape(start) + r".*?" + re.escape(end)
    if len(re.findall(pattern, text, re.S)) != 1:
        raise ValueError(f"Expected exactly one generated block: {name}")
    return re.sub(pattern, lambda _: f"{start}\n{body.strip()}\n{end}", text, flags=re.S)


def directory_lines(docs: list[dict], source: Path, root: Path = ROOT, category: int | None = None) -> list[str]:
    depth: dict[str, int] = {}
    lines = []
    for doc in docs:
        depth[doc["p"]] = depth.get(doc["parent"], -1) + 1
        if category is not None and (doc["c"] != category or not doc["parent"]):
            continue
        indent = depth[doc["p"]] - (1 if category is not None else 0)
        lines.append("    " * indent + "- " + md_link(doc["t"], relative(doc["p"], source, root)))
    return lines


def outputs(root: Path = ROOT) -> dict[Path, str]:
    catalog = build_catalog(root)
    docs, stats = catalog["docs"], catalog["stats"]
    js = "// Generated by tools/check/generate_catalog.py; do not edit.\n"
    js += "const DOCS = " + json.dumps(docs, ensure_ascii=False, indent=2) + ";\n"
    js += "const CONTENT_STATS = " + json.dumps(stats, ensure_ascii=False, indent=2) + ";\n"
    js += "const LEARNING_PATHS = " + json.dumps(catalog["paths"], ensure_ascii=False, indent=2) + ".map(p => ({...p, paths: new Set(p.paths)}));\n"
    js += "\nfunction contentHref(path) {\n  return '../' + path.split('/').map(encodeURIComponent).join('/');\n}\n"
    js += "\nfunction contentText(value) {\n  return String(value).replace(/[&<>\"']/g, char => ({'&': '&amp;', '<': '&lt;', '>': '&gt;', '\"': '&quot;', \"'\": '&#39;'}[char]));\n}\n"
    result = {root / "nav/content-data.js": js}

    index = root / "INDEX.md"
    lines = ["# GameDevMind 文档索引", "", "> 由 `python tools/check/generate_catalog.py` 自动生成，请勿手动编辑。", "",
             "## 按能力模块分类", ""]
    for doc in docs:
        if not doc["parent"]:
            lines += [f"### {doc['c']}. {doc['t']}", "", "- " + md_link(doc["t"], doc["p"])]
            lines += directory_lines(docs, index, root, doc["c"]) + [""]
            source = root / doc["p"]
            body = "\n".join(directory_lines(docs, source, root, doc["c"]))
            result[source] = replace_block(source.read_text(encoding="utf-8-sig"), "module-index", body)
    lines += ["## 专题与说明", ""]
    lines += ["- " + md_link(title_of(root / p), p) for p in catalog["supplementary"]]
    lines += ["", "## 统计口径", "", f"- **总文档数**: {stats['documents']}（`mds/` 下全部 Markdown 文件）",
              f"- **核心文档**: {stats['core']}（六大能力域，含目录页）",
              f"- **专题与说明**: {stats['supplementary']}（含阅读说明、专题及保留的历史入口）", ""]
    result[index] = "\n".join(lines)
    result[root / "KEYWORDS.md"] = render_keywords(root)

    source = root / "README.md"
    text = source.read_text(encoding="utf-8-sig")
    body = (f"| 📚 {stats['documents']} 篇文档 | 💻 {stats['codeCollections']} 类代码示例 | 🏥 {stats['cases']} 个实战案例 | 🤖 {stats['aiCases']} 个 AI 对话 |\n"
            "|:---:|:---:|:---:|:---:|\n"
            "| [浏览文档](INDEX.md) | [运行代码](code/README.md) | [查看案例](cases/README.md) | [查看对话](ai-cases/README.md) |\n\n"
            f"文档统计覆盖 `mds/` 全部 Markdown：{stats['core']} 篇核心文档（含目录页）＋ {stats['supplementary']} 篇专题与说明。")
    text = replace_block(text, "content-stats", body)
    text = re.sub(r"查看全部 \d+ 个案例", f"查看全部 {stats['cases']} 个案例", text)
    text = re.sub(r"查看全部 \d+ 个 AI 对话", f"查看全部 {stats['aiCases']} 个 AI 对话", text)
    result[source] = text
    source = root / "mds/topics/推荐阅读路径.md"
    text = source.read_text(encoding="utf-8-sig")
    body = f"本指南将《游戏开发图谱》{stats['documents']} 篇文档组织为三条可执行的学习路径，配合配套代码、实战案例与 AI 协作记录使用。"
    text = replace_block(text, "document-count", body)
    text = re.sub(r"(\| 实战案例 \|[^\n]+\| )\d+( \|)", rf"\g<1>{stats['cases']}\2", text)
    text = re.sub(r"(\| AI 协作记录 \|[^\n]+\| )\d+( \|)", rf"\g<1>{stats['aiCases']}\2", text)
    result[source] = text
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail on stale output; do not write files")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if not path.is_file() or path.read_text(encoding="utf-8-sig") != content:
            stale.append(path.relative_to(ROOT).as_posix())
            if not args.check:
                path.write_text(content, encoding="utf-8", newline="\n")
    print(("Stale generated files: " if args.check else "Updated generated files: ") + (", ".join(stale) or "none"))
    if stale and args.check:
        print("Run: python tools/check/generate_catalog.py")
    return int(args.check and bool(stale))


if __name__ == "__main__":
    raise SystemExit(main())
